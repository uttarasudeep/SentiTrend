"""SentiTrend offline batch analytics: Spark RDD, Spark SQL and Spark MLlib.

Reads data/processed_posts.jsonl relative to this script. The stream's existing
sentiment labels are generated by VADER, so model evaluation measures agreement
with those labels, not independently verified human sentiment.
"""
from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path
from operator import add
from typing import Any

from pyspark import StorageLevel
from pyspark.sql import SparkSession, functions as F
from pyspark.sql.types import StructType, StructField, StringType
from pyspark.ml import Pipeline
from pyspark.ml.feature import RegexTokenizer, StopWordsRemover, CountVectorizer, IDF, StringIndexer
from pyspark.ml.classification import LogisticRegression
from pyspark.ml.evaluation import MulticlassClassificationEvaluator


PROJECT_DIR = Path(__file__).resolve().parent
INPUT_PATH = PROJECT_DIR / "data" / "processed_posts.jsonl"


def pick(record: Any, candidates: list[str], default: Any = "") -> Any:
    """Find a field case-insensitively, including common nested post envelopes."""
    if not isinstance(record, dict):
        return default

    lowered = {str(key).lower(): value for key, value in record.items()}
    for candidate in candidates:
        value = lowered.get(candidate.lower())
        if isinstance(value, dict):
            nested = pick(value, candidates, default="")
            if nested not in (None, ""):
                return nested
        elif value not in (None, ""):
            return value

    for container in ("post", "record", "data", "value"):
        child = lowered.get(container)
        if isinstance(child, dict):
            nested = pick(child, candidates, default="")
            if nested not in (None, ""):
                return nested
    return default


def normalize_record(record: Any) -> dict[str, str]:
    """Map source records into the four fields used by batch analytics."""
    text_value = pick(record, ["text", "post_text", "content", "message", "body"], "")
    text = str(text_value).strip() if text_value is not None else ""

    raw_label = pick(
        record,
        ["sentiment", "sentiment_label", "predicted_sentiment", "label"],
        "Unknown",
    )
    label = str(raw_label).strip().lower()
    if label in {"positive", "pos"}:
        sentiment = "Positive"
    elif label in {"negative", "neg"}:
        sentiment = "Negative"
    elif label in {"neutral", "neu"}:
        sentiment = "Neutral"
    else:
        sentiment = "Unknown"

    source_value = pick(record, ["source", "platform"], "Bluesky")
    source = str(source_value).strip() if source_value is not None else "Bluesky"
    if not source:
        source = "Bluesky"

    timestamp_value = pick(record, ["created_at", "timestamp", "indexed_at", "time"], "")
    created_at = str(timestamp_value).strip() if timestamp_value is not None else ""
    return {
        "text": text,
        "sentiment": sentiment,
        "source": source,
        "created_at": created_at,
    }


def parse_json_line(line: str) -> dict[str, str] | None:
    """Parse one JSONL row safely; malformed lines are skipped and counted later."""
    try:
        parsed = json.loads(line)
    except (json.JSONDecodeError, TypeError):
        return None
    if not isinstance(parsed, dict):
        return None
    return normalize_record(parsed)


def main() -> None:
    if not INPUT_PATH.is_file():
        raise FileNotFoundError(
            f"Input file not found: {INPUT_PATH}\n"
            "Make sure data/processed_posts.jsonl exists in your SentiTrend project folder."
        )

    spark = (
        SparkSession.builder
        .appName("SentiTrend-Batch-Analytics")
        .master("local[4]")
        .config("spark.sql.shuffle.partitions", "8")
        .getOrCreate()
    )
    spark.sparkContext.setLogLevel("WARN")

    try:
        print("\n========== 1) SPARK RDD: TRANSFORMATIONS AND ACTIONS ==========")
        lines_rdd = spark.sparkContext.textFile(str(INPUT_PATH)).filter(
            lambda line: bool(line.strip())
        )
        parsed_rdd = lines_rdd.map(parse_json_line)
        malformed_count = parsed_rdd.filter(lambda row: row is None).count()
        valid_rdd = (
            parsed_rdd
            .filter(lambda row: row is not None and bool(row["text"]))
            .persist(StorageLevel.MEMORY_AND_DISK)
        )

        total_posts = valid_rdd.count()
        print(f"Usable posts read (RDD count action): {total_posts}")
        print(f"Malformed/non-object JSON records skipped: {malformed_count}")
        if total_posts == 0:
            raise ValueError(
                "No usable post text was found. Check the JSONL format and confirm "
                "that records contain a text/content/body field."
            )

        sentiment_counts = (
            valid_rdd
            .map(lambda row: (row["sentiment"], 1))
            .reduceByKey(add)
            .collect()
        )
        print("RDD sentiment counts (map + reduceByKey + collect):")
        for label, count in sorted(sentiment_counts):
            print(f"  {label}: {count}")

        # The streaming cache is capped at 2,000 records; this bounded collection
        # creates a small local DataFrame for SQL and MLlib analysis.
        rows = valid_rdd.collect()
        schema = StructType([
            StructField("text", StringType(), nullable=False),
            StructField("sentiment", StringType(), nullable=False),
            StructField("source", StringType(), nullable=False),
            StructField("created_at", StringType(), nullable=False),
        ])
        df = spark.createDataFrame(rows, schema=schema).persist(StorageLevel.MEMORY_AND_DISK)

        print("\n========== 2) SPARK SQL QUERIES ==========")
        df.createOrReplaceTempView("sentitrend_posts")

        print("SQL Query A: number of posts by sentiment")
        spark.sql("""
            SELECT sentiment, COUNT(*) AS post_count
            FROM sentitrend_posts
            GROUP BY sentiment
            ORDER BY post_count DESC, sentiment
        """).show(truncate=False)

        print("SQL Query B: sentiment by source")
        spark.sql("""
            SELECT source, sentiment, COUNT(*) AS post_count
            FROM sentitrend_posts
            GROUP BY source, sentiment
            ORDER BY source, post_count DESC, sentiment
        """).show(truncate=False)

        print("SQL Query C: data quality summary")
        spark.sql("""
            SELECT
                COUNT(*) AS total_posts,
                SUM(CASE WHEN TRIM(text) = '' THEN 1 ELSE 0 END) AS empty_text_posts,
                SUM(CASE WHEN sentiment = 'Unknown' THEN 1 ELSE 0 END) AS unknown_sentiment_posts,
                SUM(CASE WHEN TRIM(source) = '' THEN 1 ELSE 0 END) AS empty_source_posts
            FROM sentitrend_posts
        """).show(truncate=False)

        print("\n========== 3) SPARK MLlib: SENTIMENT CLASSIFIER ==========")
        labeled = (
            df.filter(F.col("sentiment").isin("Positive", "Negative", "Neutral"))
              .filter(F.length(F.trim(F.col("text"))) > 0)
              .persist(StorageLevel.MEMORY_AND_DISK)
        )
        labeled_count = labeled.count()
        class_counts = {
            row["sentiment"]: row["count"]
            for row in labeled.groupBy("sentiment").count().collect()
        }
        print(f"Usable labeled rows: {labeled_count}")
        print(f"Class counts: {class_counts}")

        if len(class_counts) < 2 or min(class_counts.values(), default=0) < 2:
            print(
                "Skipping MLlib training: at least two sentiment classes with at least "
                "two rows per class are required. RDD and SQL results are still valid."
            )
            labeled.unpersist()
        else:
            train_df, test_df = labeled.randomSplit([0.8, 0.2], seed=42)
            train_count = train_df.count()
            test_count = test_df.count()
            train_class_count = train_df.select("sentiment").distinct().count()

            evaluate_holdout = train_class_count >= 2 and test_count > 0
            if not evaluate_holdout:
                print(
                    "Warning: the random holdout split is too small or has fewer than "
                    "two training classes. Fitting on all labeled data; no holdout "
                    "accuracy will be reported."
                )
                train_df = labeled
                test_df = None
            else:
                print(f"Training rows: {train_count}; holdout rows: {test_count}")

            tokenizer = RegexTokenizer(
                inputCol="text", outputCol="tokens", pattern="\\W+", toLowercase=True
            )
            remover = StopWordsRemover(inputCol="tokens", outputCol="filtered_tokens")
            vectorizer = CountVectorizer(
                inputCol="filtered_tokens", outputCol="term_frequency", vocabSize=20000, minDF=1.0
            )
            idf = IDF(inputCol="term_frequency", outputCol="features")
            indexer = StringIndexer(
                inputCol="sentiment", outputCol="label", handleInvalid="keep"
            )
            classifier = LogisticRegression(
                featuresCol="features", labelCol="label", maxIter=20, regParam=0.01
            )
            pipeline = Pipeline(stages=[tokenizer, remover, vectorizer, idf, indexer, classifier])
            model = pipeline.fit(train_df)

            if test_df is not None:
                predictions = model.transform(test_df).persist(StorageLevel.MEMORY_AND_DISK)
                prediction_count = predictions.count()
                if prediction_count > 0:
                    evaluator = MulticlassClassificationEvaluator(
                        labelCol="label", predictionCol="prediction", metricName="accuracy"
                    )
                    accuracy = evaluator.evaluate(predictions)
                    print(
                        "Holdout accuracy against existing VADER-generated labels: "
                        f"{accuracy:.4f} ({prediction_count} evaluated rows)"
                    )
                    print(
                        "Interpretation: this measures agreement with VADER pseudo-labels, "
                        "not accuracy against human-verified sentiment."
                    )
                    predictions.select("text", "sentiment", "prediction").show(
                        10, truncate=80
                    )
                else:
                    print("The holdout produced no evaluable predictions; accuracy omitted.")
                predictions.unpersist()
            else:
                print("Showing sample predictions on training rows only; no accuracy reported.")
                model.transform(train_df).select("text", "sentiment", "prediction").show(
                    10, truncate=80
                )

            # Create a new timestamped model directory instead of overwriting an existing model.
            model_dir = PROJECT_DIR / "models"
            model_dir.mkdir(parents=True, exist_ok=True)
            timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
            model_path = model_dir / f"sentiment_mllib_model_{timestamp}"
            model.write().save(str(model_path))
            print(f"Saved MLlib pipeline model to: {model_path}")
            labeled.unpersist()

        df.unpersist()
        valid_rdd.unpersist()
        print("\nDONE: Spark RDD, Spark SQL, and MLlib analytics run finished.")
    finally:
        spark.stop()


if __name__ == "__main__":
    main()
